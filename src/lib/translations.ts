// English UI calls money received from residents "collections" (matching
// the Arabic التحصيلات); the code and string keys still say "payment"
export function englishWording(text: string): string {
  return text.replace(/\b([Pp])ayment(s?)\b/g, (_, p: string, s: string) => (p === "P" ? "Collection" : "collection") + s)
}

